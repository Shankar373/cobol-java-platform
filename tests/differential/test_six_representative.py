"""
tests/differential/test_six_representative.py

Six-Program Differential Validation Test Suite — Mentor Deliverable
=====================================================================

Runs the 4-step DifferentialVerifier for all six representative programs:

  1. SIMPLEBASELINE01  — COBOL-only business logic + file output
  2. ACCTPROG          — COBOL + COPYBOOK + external CALL + file output
  3. MULTIFILE01       — Sequential multi-file processing
  4. DB2SELECT01       — EXEC SQL / PostgreSQL (real DB, no mock)
  5. JCLBATCH01        — JCL compatibility orchestration
  6. CICSREST01        — CICS compatibility workload

Each test asserts the business equivalence verdict is NOT FAIL and NOT BLOCKED
(PASS, WARNING, or UNPROVEN are acceptable depending on workload classification).

Evidence:
  - reports/<program>/differential_validation_report.{md,json}
  - Assertions below verify what each workload PROVES and DOES NOT PROVE.
"""

