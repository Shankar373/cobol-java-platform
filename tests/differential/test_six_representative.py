def _assert_mandatory_report_structure(report: dict, program: str):
    """Every report must have all required classification dimensions."""
    required_keys = [
        "program", "repository", "generated_at", "target_jdk",
        "conversion", "compilation", "cobol_runtime", "java_runtime",
        "comparison", "file_comparison_detail",
        "unsupported_constructs", "warnings", "mock_components",
        "business_equivalence",
    ]
    for k in required_keys:
        assert k in report, f"[{program}] Report missing key: {k}"

    comparison = report["comparison"]
    for dim in ("stdout", "exit_code", "files", "database"):
        assert dim in comparison, f"[{program}] comparison.{dim} missing"

    valid_verdicts = {"PASS", "WARNING", "FAIL", "UNPROVEN", "BLOCKED"}
    assert report["business_equivalence"] in valid_verdicts, \
        f"[{program}] Invalid verdict: {report['business_equivalence']}"


def _assert_not_false_pass(report: dict, program: str, mock_in_use: bool):
    """
    If any mock component was used and affected a required comparison, the
    verdict MUST NOT be PASS.
    Compilation alone MUST NOT produce PASS.
    """
    be = report["business_equivalence"]
    cobol_rt = report["cobol_runtime"]["status"]
    java_rt   = report["java_runtime"]["status"]

    # Compilation success alone must never produce PASS
    if cobol_rt in ("UNPROVEN", "BLOCKED", "FAIL") or java_rt in ("UNPROVEN", "BLOCKED", "FAIL"):
        assert be != "PASS", (
            f"[{program}] FALSE PASS: PASS verdict issued without real execution "
            f"(cobol_rt={cobol_rt}, java_rt={java_rt})"
        )

    if mock_in_use:
        assert be != "PASS", (
            f"[{program}] FALSE PASS: PASS verdict issued while mock components "
            f"were in use: {report['mock_components']}"
        )


