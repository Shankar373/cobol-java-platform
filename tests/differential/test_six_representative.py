def _load_report(reports_dir: str, program: str) -> dict:
    """Load the JSON report generated by the verifier."""
    p = os.path.join(reports_dir, program, "differential_validation_report.json")
    assert os.path.isfile(p), f"Report not generated: {p}"
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


def run_verifier(repo_name: str, tmp_dir: str) -> tuple:
    """Run DifferentialVerifier, return (verdict, report_dict)."""
    repo_dir = os.path.join(REPOS, repo_name)
    assert os.path.isdir(repo_dir), f"Fixture repo not found: {repo_dir}"

    out_dir = os.path.join(tmp_dir, repo_name)
    os.makedirs(out_dir, exist_ok=True)

    v = DifferentialVerifier(repo_dir=repo_dir, out_dir=out_dir, program_name=repo_name)
    verdict = v.run_all()

    # Load the generated report for further assertions
    reports_dir = os.path.join(out_dir, "reports")
    report = _load_report(reports_dir, repo_name)
    return verdict, report


