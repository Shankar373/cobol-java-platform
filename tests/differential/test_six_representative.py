# 1. SIMPLEBASELINE01 — COBOL-only, file output
# ============================================================================

@pytest.mark.differential
def test_simplebaseline01(tmp_path):
    """
    PROVES:
      - Real COBOL compiled+executed (GnuCOBOL Docker)
      - Real Java 17+ compiled+executed (JVM Docker)
      - Identical STATE A: stdout + output file compared
      - No mock components
      - Business Equivalence PASS is achievable

    DOES NOT PROVE:
      - DB2/z or CICS behavior
      - z/OS-specific numeric encoding edge cases
    """
    verdict, report = run_verifier("SIMPLEBASELINE01", str(tmp_path))

    _assert_mandatory_report_structure(report, "SIMPLEBASELINE01")
    _assert_not_false_pass(report, "SIMPLEBASELINE01", mock_in_use=False)

    # Must not be FAIL or BLOCKED
    assert verdict not in ("FAIL", "BLOCKED"), (
        f"SIMPLEBASELINE01 returned unexpected verdict: {verdict}\n"
        f"Compilation: {report['compilation']}\n"
        f"COBOL Runtime: {report['cobol_runtime']['status']}\n"
        f"Java Runtime: {report['java_runtime']['status']}"
    )

    # Compilation must have passed
    assert report["compilation"]["status"] in ("PASS",), \
        f"Compilation did not PASS: {report['compilation']}"

    # Report must identify the converted file(s)
    assert len(report["conversion"]["files"]) > 0, \
        "No converted Java files recorded"

    print(f"\n  SIMPLEBASELINE01 Business Equivalence: {verdict}")
    print(f"  What this PROVES: COBOL→Java stdout+file parity under identical conditions")


