@pytest.mark.differential
def test_all_reports_generated(tmp_path):
    """
    Verify all 6 reports are generated, have the correct structure, and
    contain the mandatory mentor classification dimensions.
    """
    programs = [
        "SIMPLEBASELINE01",
        "ACCTPROG",
        "MULTIFILE01",
        "DB2SELECT01",
        "JCLBATCH01",
        "CICSREST01",
    ]

    for prog in programs:
        repo_dir = os.path.join(REPOS, prog)
        if not os.path.isdir(repo_dir):
            pytest.skip(f"Fixture repo not found: {prog}")

        out_dir = os.path.join(str(tmp_path), prog)
        os.makedirs(out_dir, exist_ok=True)

        v = DifferentialVerifier(repo_dir=repo_dir, out_dir=out_dir, program_name=prog)
        verdict = v.run_all()
        report_path = os.path.join(out_dir, "reports", prog,
                                   "differential_validation_report.json")
        assert os.path.isfile(report_path), f"[{prog}] JSON report not generated"

        md_path = os.path.join(out_dir, "reports", prog,
                               "differential_validation_report.md")
        assert os.path.isfile(md_path), f"[{prog}] Markdown report not generated"

        with open(report_path) as fh:
            report = json.load(fh)

        _assert_mandatory_report_structure(report, prog)

        # Verify no verdict collapses
        be = report["business_equivalence"]
        assert be != "", f"[{prog}] Empty business_equivalence"
        print(f"  [{prog}] Business Equivalence: {be}")
