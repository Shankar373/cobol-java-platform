def _init_from_node(props: dict, ti: JavaTypeInfo) -> str:
    """Derive the Java initialisation expression from PIC VALUE clause."""
    val = props.get("value", props.get("initial_value"))
    if val is None:
        return ti.init_expr

    val_str = str(val).strip()
    if val_str.upper() in ("ZERO", "ZEROS", "ZEROES"):
        return ti.init_expr if "0" in ti.init_expr or "ZERO" in ti.init_expr else "0"
    if val_str.upper() in ("SPACE", "SPACES"):
        return '""'
    if val_str.upper() in ("HIGH-VALUE", "HIGH-VALUES"):
        return '"\\xFF"'
    if ti.is_alpha:
        inner = val_str.strip("'\"")
        return f'"{inner}"'
    if ti.is_numeric:
        try:
            int(val_str)
            return val_str
        except ValueError:
            try:
                float(val_str)
                return val_str
            except ValueError:
                pass
    return ti.init_expr


def _write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
